<?php

/*
 * Builds lang/{en,es,pt}/countries.php: every region libphonenumber can read a
 * phone number for, named by ICU in each language and sorted the way that
 * language sorts. The attendee phone's country selector reads these files
 * (PLAN 10.16), so the app needs neither ext-intl nor a request at runtime.
 *
 * Re-run after a libphonenumber update only if CountryListTest says a code is
 * no longer supported. Needs ext-intl, which the Sail container has:
 *
 *   docker compose exec laravel.test php scripts/generate-countries.php
 */

require __DIR__.'/../vendor/autoload.php';

use libphonenumber\PhoneNumberUtil;

$regions = PhoneNumberUtil::getInstance()->getSupportedRegions();

foreach (['en', 'es', 'pt'] as $locale) {
    $names = [];

    foreach ($regions as $region) {
        $name = Locale::getDisplayRegion('-'.$region, $locale);

        if ($name === false || $name === '' || $name === $region) {
            fwrite(STDERR, "[{$locale}] ICU has no name for {$region}\n");
            exit(1);
        }

        $names[$region] = $name;
    }

    $collator = new Collator($locale);
    uasort($names, fn (string $a, string $b): int => (int) $collator->compare($a, $b));

    $lines = array_map(
        fn (string $code, string $name): string => '    '.var_export($code, true).' => '.var_export($name, true).',',
        array_keys($names),
        $names,
    );

    $php = "<?php\n\n"
        ."// Generated by scripts/generate-countries.php — do not edit by hand.\n"
        ."// Regions libphonenumber supports, named and sorted for this language.\n\n"
        ."return [\n".implode("\n", $lines)."\n];\n";

    file_put_contents(__DIR__."/../lang/{$locale}/countries.php", $php);
    echo "lang/{$locale}/countries.php: ".count($names)." countries\n";
}
